#!/usr/bin/env python3
"""export_board.py - trained model -> everything the FPGA build needs (ROMs, model configuration module, manifest) + the vectors of the system-level simulation

Inputs: a training run (float_folded.npz, anchors.json, metrics.json / eval_int.json if present) and the data directory (calibration images, a sample test image).
Outputs (--rtl-out, normally the custom/ folder of the TD project):
  yolo_desc_rom.v  yolo_wt_rom.v  yolo_pm_rom.v      descriptor table (34 layers: 3 letterbox fills, 16 border fills, 13 convolutions, pool9, upsample), weights, per-channel {bias, M, S}
  yolo_model_cfg.v                                  module yolo_model_cfg (output nlayers, anc1, anc2): the model constants yolo_top needs
and (--case-out): the mininet case files of the board geometry (128 x 96, letterbox 12 / 72) for tb_yolo_net.v, the sample image as a 1280 x 720 frame for tb_yolo_top.v
(each 10 x 10 block filled with the colour of one network-input pixel, so the board's average reproduces the image exactly), the expected boxes (decode_ref, hardware operating
point) and <case>_manifest.json (topology, scales, anchors, metrics, SHA256 of every ROM).
Usage: F:/yolo_env/Scripts/python.exe export_board.py --run F:/yolo_runs/p5_synth --data F:/yolo_data --rtl-out <dir> --case-out F:/fpga_s2/logs_custom/yolo_vec/board
"""
import argparse
import hashlib
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import quantize as qz
import mininet
import gen_rom
import decode_ref as dr
import eval_int as ei

CH = ei.CH
DEPTHS = dict(A=38220, B=26400, C=2560, D=1440)      # must match the yolo_top parameters


def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


def pack_anchors(anc):
    v = 0
    for a, (w, h) in enumerate(anc):
        v |= (int(w) & 0xFF) << (16 * a)
        v |= (int(h) & 0xFF) << (16 * a + 8)
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--run', default='F:/yolo_runs/p5_synth')
    ap.add_argument('--data', default='F:/yolo_data')
    ap.add_argument('--rtl-out', required=True)
    ap.add_argument('--case-out', default=os.path.normpath(os.path.join(HERE, '..', '..', '..', 'logs_custom', 'yolo_vec', 'board')))
    ap.add_argument('--calib', type=int, default=256)
    ap.add_argument('--sample', type=int, default=-1, help='index of the test image used for the system simulation (default: the first one with >= 3 objects)')
    a = ap.parse_args()
    os.makedirs(a.rtl_out, exist_ok=True)
    os.makedirs(a.case_out, exist_ok=True)
    z = np.load(os.path.join(a.run, 'float_folded.npz'))
    P = {k: (z[k + '_w'], z[k + '_b']) for k in qz.NAMES}
    anchors = json.load(open(os.path.join(a.run, 'anchors.json')))['anchors']
    tr = np.load(os.path.join(a.data, 'train_img.npy'), mmap_mode='r')
    rng = np.random.default_rng(1)                                           # the same calibration set as eval_int.py
    calib = [(tr[i].astype(np.float64) - 128.0) / 128.0 for i in rng.choice(len(tr), a.calib, replace=False)]
    qp, scales, rep = qz.quantize(P, calib, CH)
    te = np.load(os.path.join(a.data, 'test_img.npy'), mmap_mode='r')
    te_lab = json.load(open(os.path.join(a.data, 'test_lab.json')))
    idx = a.sample if a.sample >= 0 else next(i for i, l in enumerate(te_lab) if len(l) >= 3)
    img_u8 = np.array(te[idx])
    img_i8 = (img_u8.astype(np.int16) - 128).astype(np.int8)
    prefix = os.path.join(a.case_out, 'board')
    info = mininet.write_case(prefix, 128, 96, CH, 8, 0, qparams=qp, image=img_i8, letterbox=(12, 72))
    for k, nm in ((0, 'A'), (1, 'B'), (2, 'C'), (3, 'D')):
        assert info['bank_bytes'][k] == DEPTHS[nm], ('bank %s needs %d bytes, yolo_top has %d' % (nm, info['bank_bytes'][k], DEPTHS[nm]))
    nl = len(info['layers'])
    assert nl < 64
    # ROMs
    for kind, width, aw, name in (('desc', 208, 6, 'desc_rom'), ('wt', 64, 14, 'wt_rom'), ('pm', 56, 11, 'pm_rom')):
        src = prefix + '_%s.hex' % kind
        lines = [l for l in open(src).read().split() if l]
        gen_rom.write_rom(os.path.join(a.rtl_out, 'yolo_%s.v' % name), 'yolo_%s' % name, width, len(lines), aw, lines, src,
                          {'desc': 'layer descriptor table of yolo_net_engine (board model)', 'wt': 'weights of the board model, tile-major, lane 0 = least significant byte',
                           'pm': 'per output channel {bias[53:22], multiplier[21:6], shift[5:0]} of the board model'}[kind])
    anc1, anc2 = pack_anchors(anchors[0]), pack_anchors(anchors[1])
    cfg_path = os.path.join(a.rtl_out, 'yolo_model_cfg.v')
    with open(cfg_path, 'w', newline='\n') as f:
        f.write('// yolo_model_cfg.v - GENERATED by tools/yolo/train/export_board.py from %s, do not edit by hand\n' % a.run.replace('\\', '/'))
        f.write('// model constants of the detector: number of descriptors, anchors (network pixels, anchor a = width [16a +: 8], height [16a + 8 +: 8])\n')
        f.write('// head 1 (stride 32): %s   head 2 (stride 16): %s\n\n' % (anchors[0], anchors[1]))
        f.write('module yolo_model_cfg (\n    output wire [5:0]  nlayers,\n    output wire [47:0] anc1,\n    output wire [47:0] anc2\n);\n')
        f.write("    assign nlayers = 6'd%d;\n    assign anc1 = 48'h%012X;\n    assign anc2 = 48'h%012X;\nendmodule\n" % (nl, anc1, anc2))
    # system-simulation frame: every 10 x 10 block = one network-input pixel of the image rows
    frame = np.repeat(np.repeat(img_u8[12:84], 10, axis=0), 10, axis=1)                 # 720 x 1280 x 3
    with open(os.path.join(a.case_out, 'board_frame.hex'), 'w') as f:
        for v in frame.reshape(-1, 3):
            f.write('%02X%02X%02X\n' % tuple(int(c) for c in v))
    cfg = ei.cfg_from_anchors(anchors)
    h1, h2 = ei.int_forward(img_i8, qp)
    assert np.array_equal(h1, info['head1']) and np.array_equal(h2, info['head2']), 'int_forward and mininet disagree'
    boxes = dr.decode([h1, h2], cfg)
    with open(os.path.join(a.case_out, 'board_boxes.hex'), 'w') as f:
        f.write('%d\n' % len(boxes))
        for (score, cls, x0, y0, x1, y1) in boxes:
            f.write('%015X\n' % ((cls << 58) | (score << 42) | (x0 << 31) | (y0 << 21) | (x1 << 10) | y1))
    metrics = {}
    for fn in ('metrics.json', 'eval_int.json'):
        p = os.path.join(a.run, fn)
        if os.path.exists(p):
            m = json.load(open(p))
            m.pop('quant_report', None)
            metrics[fn] = m
    man = qz.write_manifest(prefix, CH, 128, 96, 8, scales, note='trained model %s; sample test image %d' % (a.run, idx))
    man['anchors'] = anchors
    man['nlayers'] = nl
    man['rom_sha256'] = {os.path.basename(p): sha(p) for p in [os.path.join(a.rtl_out, n) for n in ('yolo_desc_rom.v', 'yolo_wt_rom.v', 'yolo_pm_rom.v', 'yolo_model_cfg.v')]}
    man['metrics'] = metrics
    man['sample_boxes'] = [dict(cls=int(c), score=round(s / 65536.0, 3), x0=x0, y0=y0, x1=x1, y1=y1) for (s, c, x0, y0, x1, y1) in boxes]
    man['sample_labels_net'] = te_lab[idx]
    json.dump(man, open(prefix + '_manifest.json', 'w'), indent=1)
    print('descriptors %d, weight words %d, params %d, anchors %s' % (nl, info['wt_words'], info['pm'], anchors))
    print('sample test image %d: %d labels, %d boxes from the integer network: %s' % (idx, len(te_lab[idx]), len(boxes), man['sample_boxes']))
    print('ROMs + yolo_model_cfg.v ->', a.rtl_out)


if __name__ == '__main__':
    main()
