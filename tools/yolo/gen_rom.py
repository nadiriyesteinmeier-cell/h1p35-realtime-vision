#!/usr/bin/env python3
"""gen_rom.py - turn the memory images of a network (mininet.py now, the exported model later) into synthesizable ROM modules for yolo_net_engine

Usage: python gen_rom.py <case prefix, e.g. logs_custom/yolo_vec/net8/net_a> <output directory> [--lanes 8] [--prefix yolo]
Writes <prefix>_desc_rom.v (208 bit x layers), <prefix>_wt_rom.v (8 * lanes bit x words) and <prefix>_pm_rom.v (56 bit x channels), each a module
  module <name> (input clk, input [AW-1:0] addr, output reg [W-1:0] data);        synchronous read, 1 clock
in the style of TD's own ROM template (array + 'initial' with non-blocking assignments + (* rom_style = "bram" *); the same style as rtl_custom/osd_logo_rom.v,
which TD maps to ERAM with initial contents). GENERATED files: do not edit by hand, regenerate from the model package (hashes in the header).
"""
import argparse
import hashlib
import os


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()[:16]


def write_rom(path, name, width, depth, awidth, lines, src, comment):
    with open(path, 'w', newline='\n') as f:
        f.write('// %s - GENERATED by tools/yolo/gen_rom.py, do not edit by hand\n' % os.path.basename(path))
        f.write('// %s\n// source image: %s (sha256 prefix %s), %d words of %d bits, synchronous read (1 clock), addresses >= %d are not defined\n\n' % (
            comment, os.path.basename(src), sha(src), depth, width, depth))
        f.write('module %s (\n    input  wire              clk,\n    input  wire [%d:0] addr,\n    output reg  [%d:0] data\n);\n\n' % (name, awidth - 1, width - 1))
        f.write('    (* rom_style = "bram" *) reg [%d:0] mem [0:%d];\n\n    initial begin\n' % (width - 1, depth - 1))
        hexw = (width + 3) // 4
        for i, l in enumerate(lines):
            f.write("        mem[%d] <= %d'h%s;\n" % (i, width, l.strip().upper().rjust(hexw, '0')))
        ab = max(1, (depth - 1).bit_length())                      # TD infers ERAM only if the index has exactly ceil(log2(depth)) bits (tools/td_exp/ram_probe_m.v)
        f.write('    end\n\n    always @(posedge clk) data <= mem[addr[%d:0]];\n\nendmodule\n' % (ab - 1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('case')
    ap.add_argument('outdir')
    ap.add_argument('--lanes', type=int, default=8)
    ap.add_argument('--prefix', default='yolo')
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    for kind, width, aw, name in (('desc', 208, 6, 'desc_rom'), ('wt', 8 * a.lanes, 14, 'wt_rom'), ('pm', 56, 11, 'pm_rom')):
        src = a.case + '_%s.hex' % kind
        lines = [l for l in open(src).read().split() if l]
        write_rom(os.path.join(a.outdir, '%s_%s.v' % (a.prefix, name)), '%s_%s' % (a.prefix, name), width, len(lines), aw, lines, src,
                  {'desc': 'layer descriptor table of yolo_net_engine', 'wt': 'weights, tile-major, one word per tap and tile (lane 0 = least significant byte)',
                   'pm': 'per output channel {bias[53:22], multiplier[21:6], shift[5:0]} (56-bit word, top 2 bits 0)'}[kind])
        print('%-22s %5d words x %3d bit' % ('%s_%s.v' % (a.prefix, name), len(lines), width))


if __name__ == '__main__':
    main()
