#!/usr/bin/env python3
"""gen_luts.py - write rtl_custom/yolo_lut_rom.v: the sigmoid and exp tables of the detection-head decoder (tools/yolo/decode_ref.py is the reference)

Usage: python gen_luts.py [output file]      (default rtl_custom/yolo_lut_rom.v)
Two modules, 256 x 16 bit, synchronous read (1 clock), address = q + 128 (offset binary: {~q[7], q[6:0]}); TD maps them to ERAM with initial contents
(same ROM style as rtl_custom/osd_logo_rom.v). Floating point is used here, at generation time, only.
"""
import os
import sys

import decode_ref as dr


def rom(f, name, table, comment):
    f.write('// %s\nmodule %s (\n    input  wire        clk,\n    input  wire [7:0]  addr,\n    output reg  [15:0] data\n);\n\n' % (comment, name))
    f.write('    (* rom_style = "bram" *) reg [15:0] mem [0:255];\n\n    initial begin\n')
    for i, v in enumerate(table):
        f.write("        mem[%d] <= 16'h%04X;\n" % (i, v))
    f.write('    end\n\n    always @(posedge clk) data <= mem[addr];\n\nendmodule\n\n')


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'rtl_custom', 'yolo_lut_rom.v')
    with open(out, 'w', newline='\n') as f:
        f.write('// yolo_lut_rom.v - GENERATED by tools/yolo/gen_luts.py, do not edit by hand\n')
        f.write('// sigmoid and exp tables of yolo_decode.v for head outputs of real scale 1/16 (see tools/yolo/decode_ref.py), index = int8 value + 128\n\n')
        rom(f, 'yolo_sig_rom', dr.SIG, 'SIG[q] = min(65535, round(65536 / (1 + exp(-q / 16)))), Q16 sigmoid')
        rom(f, 'yolo_exp_rom', dr.EXPQ8, 'EXPQ8[q] = min(65535, round(256 * exp(q / 16))), Q8 exp')
    print('wrote', os.path.normpath(out))


if __name__ == '__main__':
    main()
