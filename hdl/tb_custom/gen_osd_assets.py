#!/usr/bin/env python3
"""Generate the OSD ROM assets (font + logo) as plain Verilog and as data files for the Python golden model.

Outputs
  rtl_custom/osd_font_rom.v      8x16 font ROM, 256 chars x 16 rows (ASCII 0x20..0x7E + CJK half-cells 0x80..)
  rtl_custom/osd_logo_rom.v      Anlogic logo, LOGO_W x LOGO_H, 8 bit per pixel {class[7], alpha[4:0]}
  tb_custom/osd_assets/font.npy  uint8 [256,16]    (bit 7 = leftmost pixel)
  tb_custom/osd_assets/logo.npy  uint8 [LOGO_H,LOGO_W]
  logs_custom/osd_preview/*.png  previews to look at

Sources
  ASCII glyphs : DejaVu Sans Mono (permissive Bitstream Vera / DejaVu licence), rendered 1 bit at 13 px.
  CJK glyphs   : SimHei, rendered 1 bit at 16 px, split into a left and a right 8x16 half-cell.
                 CJK_CHARS[i] -> codes 0x80+2*i (left half) and 0x81+2*i (right half).
  Logo         : pixel data of the Anlogic mark taken from the vendor reference ROM
                 lab3/.../anlogic_logo_rom.v (read only). The vendor pixels are blended with white at the
                 edges; here every pixel is converted to (colour class, 5-bit alpha 0..16) so that the logo can
                 be alpha-blended onto live video without a white halo. Overlay logic is our own.

Rerun:  python gen_osd_assets.py       (needs Pillow and numpy). Deterministic, no randomness.
"""
import os
import re
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RTL = os.path.join(ROOT, "rtl_custom")
ASSETS = os.path.join(ROOT, "tb_custom", "osd_assets")
PREVIEW = os.path.join(ROOT, "logs_custom", "osd_preview")
VENDOR_LOGO = os.path.join(ROOT, "lab3", "user_source", "hdl_source", "anlogic_logo_rom.v")
FONT_ASCII = r"C:\Windows\Fonts\DejaVuSansMono.ttf"
FONT_CJK = r"C:\Windows\Fonts\simhei.ttf"
CJK_CHARS = "安路实时视觉目标计数越线"          # 12 chars -> codes 0x80..0x97

NAVY = (28, 45, 78)
RED = (237, 28, 36)


def render_cell(font, ch, w, h, baseline, xoff=0):
    img = Image.new("1", (w, h), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((xoff, baseline), ch, font=font, fill=1, anchor="ls")
    return np.array(img, dtype=np.uint8)


def build_font():
    font = np.zeros((256, 16), dtype=np.uint8)
    f_ascii = ImageFont.truetype(FONT_ASCII, 13)
    for code in range(0x20, 0x7F):
        px = render_cell(f_ascii, chr(code), 8, 16, 12)
        for r in range(16):
            font[code, r] = int("".join(str(int(b)) for b in px[r]), 2)
    f_cjk = ImageFont.truetype(FONT_CJK, 16)
    for i, ch in enumerate(CJK_CHARS):
        px = render_cell(f_cjk, ch, 16, 16, 14)
        for r in range(16):
            font[0x80 + 2 * i, r] = int("".join(str(int(b)) for b in px[r, :8]), 2)
            font[0x81 + 2 * i, r] = int("".join(str(int(b)) for b in px[r, 8:]), 2)
    return font


def build_logo():
    src = open(VENDOR_LOGO, encoding="utf8", errors="replace").read()
    ents = re.findall(r"15'd(\d+):\s*O_pixel\s*=\s*25'h([0-9a-fA-F]+);", src)
    vendor = np.zeros((160, 160, 3), dtype=np.float64)
    listed = np.zeros((160, 160), dtype=bool)
    for a, v in ents:
        a, v = int(a), int(v, 16)
        y, x = divmod(a, 160)
        vendor[y, x] = ((v >> 16) & 255, (v >> 8) & 255, v & 255)
        listed[y, x] = True
    ys, xs = np.nonzero(listed)
    y0, y1 = ys.min(), ys.max()
    h = int(y1 - y0 + 1)
    logo = np.zeros((h, 160), dtype=np.uint8)
    worst = 0.0
    for y in range(h):
        for x in range(160):
            if not listed[y + y0, x]:
                continue
            p = vendor[y + y0, x]
            best = None
            for cls, col in ((0, NAVY), (1, RED)):
                col = np.array(col, dtype=np.float64)
                den = 255.0 - col
                use = den > 40
                a = float(np.clip(np.mean((255.0 - p[use]) / den[use]), 0.0, 1.0))
                rec = a * col + (1.0 - a) * 255.0
                err = float(np.abs(rec - p).max())
                if best is None or err < best[0]:
                    best = (err, cls, a)
            worst = max(worst, best[0])
            alpha = int(round(best[2] * 16))
            logo[y, x] = (best[1] << 7) | alpha
    return logo, int(y0), worst


ROM_NOTE = [
    "// Written in the style of TD's own ROM template (Synthesis-Structure/Directive/ROM-Inference-Styles):",
    "// array + 'initial' with non-blocking assignments + synchronous read. TD maps this to block RAM (ERAM)",
    "// with initial contents; a 'case' style ROM would become ~10k logic gates (font) and does not even finish",
    "// optimize_rtl in 280 s (logo). Every entry is initialised explicitly so simulation never sees X.",
]


def rom_module(name, doc, abits, dbits, values):
    lines = ["// %s.v - GENERATED by tb_custom/gen_osd_assets.py, do not edit by hand." % name] + doc + [""] + ROM_NOTE + [
        "",
        "module %s (" % name,
        "    input  wire        clk,",
        "    input  wire [%d:0] addr," % (abits - 1),
        "    output reg  [%d:0] data" % (dbits - 1),
        ");",
        "",
        "    (*rom_style = \"bram\"*) reg [%d:0] mem [0:%d];" % (dbits - 1, len(values) - 1),
        "",
        "    initial begin",
    ]
    for a, v in enumerate(values):
        lines.append("        mem[%d] <= %d'h%0*X;" % (a, dbits, (dbits + 3) // 4, int(v)))
    lines += ["    end", "", "    always @(posedge clk) data <= mem[addr];", "", "endmodule", ""]
    return "\n".join(lines)


def write_font_rom(font):
    doc = [
        "// 8x16 font ROM, 256 characters x 16 rows, synchronous read (1 clock).",
        "// addr = {char[7:0], row[3:0]}; data[7] is the leftmost pixel of the row.",
        "// 0x20..0x7E : ASCII (DejaVu Sans Mono, 13 px, 1 bit)",
        "// 0x80..0x97 : 12 CJK characters as left/right half cells (SimHei, 16 px, 1 bit):",
        "//              " + " ".join("0x%02X/0x%02X=%s" % (0x80 + 2 * i, 0x81 + 2 * i, "U+%04X" % ord(c)) for i, c in enumerate(CJK_CHARS)),
    ]
    open(os.path.join(RTL, "osd_font_rom.v"), "w", encoding="ascii", newline="\n").write(
        rom_module("osd_font_rom", doc, 12, 8, font.reshape(-1)))


def write_logo_rom(logo):
    h, w = logo.shape
    n = h * w
    flat = logo.reshape(-1).astype(np.uint8)
    six = (((flat >> 7) & 1) << 5) | (flat & 31)             # {class, alpha[4:0]}
    doc = [
        "// Anlogic logo, %d x %d pixels, address = row*%d + column, synchronous read (1 clock)." % (w, h, w),
        "// data = {class[5], alpha[4:0]}: class 0 = navy, 1 = red; alpha 0..16 (16 = opaque).",
        "// Pixel data derived from the vendor reference logo (lab3 anlogic_logo_rom.v), see the generator.",
        "// LOGO_W = %d, LOGO_H = %d, %d words." % (w, h, n),
    ]
    open(os.path.join(RTL, "osd_logo_rom.v"), "w", encoding="ascii", newline="\n").write(
        rom_module("osd_logo_rom", doc, max(n - 1, 1).bit_length(), 6, six))


def previews(font, logo):
    os.makedirs(PREVIEW, exist_ok=True)
    # font sheet: 16 x 16 characters, 4x scale
    sheet = np.zeros((16 * 16 * 1, 16 * 8), dtype=np.uint8)
    for code in range(256):
        cy, cx = divmod(code, 16)
        for r in range(16):
            for b in range(8):
                sheet[cy * 16 + r, cx * 8 + b] = 255 if (font[code, r] >> (7 - b)) & 1 else 0
    Image.fromarray(sheet).resize((sheet.shape[1] * 4, sheet.shape[0] * 4), Image.NEAREST).save(os.path.join(PREVIEW, "font_sheet.png"))
    # text line preview
    line = "ANLOGIC PH1P35  MODE:ORIG X:0640 Y:0360 AREA:020000"
    img = np.zeros((16, 8 * len(line) + 8 * 12), dtype=np.uint8)
    for i, ch in enumerate(line):
        for r in range(16):
            for b in range(8):
                img[r, i * 8 + b] = 255 if (font[ord(ch), r] >> (7 - b)) & 1 else 0
    for k in range(len(CJK_CHARS)):
        for half in range(2):
            col = len(line) * 8 + k * 16 + half * 8 if k < 6 else None
            if col is None:
                continue
            for r in range(16):
                for b in range(8):
                    img[r, col + b] = 255 if (font[0x80 + 2 * k + half, r] >> (7 - b)) & 1 else 0
    Image.fromarray(img).resize((img.shape[1] * 3, img.shape[0] * 3), Image.NEAREST).save(os.path.join(PREVIEW, "text_line.png"))
    # logo over three backgrounds, x2
    h, w = logo.shape
    cols = {0: np.array(NAVY, dtype=np.float64), 1: np.array(RED, dtype=np.float64)}
    out = np.zeros((h, w * 3, 3), dtype=np.uint8)
    for bi, bg in enumerate(((0, 0, 0), (90, 90, 90), (200, 200, 200))):
        for y in range(h):
            for x in range(w):
                v = int(logo[y, x])
                a, c = v & 31, (v >> 7) & 1
                rgb = (np.array(bg, dtype=np.float64) * (16 - a) + cols[c] * a) / 16.0
                out[y, bi * w + x] = np.floor(rgb).astype(np.uint8)
    Image.fromarray(out).resize((out.shape[1] * 2, out.shape[0] * 2), Image.NEAREST).save(os.path.join(PREVIEW, "logo_on_backgrounds.png"))


def main():
    os.makedirs(ASSETS, exist_ok=True)
    font = build_font()
    logo, y0, worst = build_logo()
    np.save(os.path.join(ASSETS, "font.npy"), font)
    np.save(os.path.join(ASSETS, "logo.npy"), logo)
    write_font_rom(font)
    write_logo_rom(logo)
    previews(font, logo)
    nz = int(np.count_nonzero(font))
    print("font: %d non-zero rows; logo: %dx%d (vendor rows %d..%d), non-zero pixels %d, worst colour error %.1f" %
          (nz, logo.shape[1], logo.shape[0], y0, y0 + logo.shape[0] - 1, int(np.count_nonzero(logo)), worst))
    flat = logo.reshape(-1)
    print("alpha histogram (0..16):", np.bincount((flat & 31).astype(np.int64), minlength=17).tolist())
    print("pixels with alpha>0: navy %d, red %d" % (int(np.count_nonzero(((flat >> 7) & 1 == 0) & ((flat & 31) > 0))),
                                                   int(np.count_nonzero(((flat >> 7) & 1 == 1) & ((flat & 31) > 0)))))


if __name__ == "__main__":
    sys.exit(main())
